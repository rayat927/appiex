import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = name => fs.readFileSync(name, 'utf8');
const html = read('growth-sprint.html');
const funnel = read('start-project.html');
const script = read('scripts/seo-conversion-tracker.js');
const funnelLogic = read('scripts/start-project-funnel.js');
const sitemap = read('sitemap.xml');
assert(html.includes('<meta name="robots" content="noindex, follow">'), 'Transient campaign should not compete with main services in organic search');
assert(html.includes('<link rel="canonical" href="https://appiex.com/growth-sprint">'), 'Expected campaign canonical missing');
assert(!sitemap.includes('<loc>https://appiex.com/growth-sprint</loc>'), 'Transient campaign must be omitted from sitemap');
assert.equal((html.match(/<h1\b/g)||[]).length, 1, 'Campaign must have a single H1');
assert.equal((html.match(/<article\b/g)||[]).length,3,'Three market-specific use cases required');
for(const country of ['UAE','USA','Bangladesh']) assert(html.includes(country), 'Market missing: '+country);
for(const marker of ['uae_outreach','us_outreach','bd_outreach']) assert(html.includes(marker),'Market attribution missing: '+marker);
assert((html.match(/href="\/start-project\?/g)||[]).length >= 3, 'Qualification handoff links missing');
assert(html.includes('/scripts/seo-conversion-tracker.js'), 'Lead event tracking missing from campaign');
assert(funnel.includes('/scripts/seo-conversion-tracker.js'), 'Project-fit funnel must load GA4 tracking');
assert(script.includes("window.addEventListener('appiex:lead_received'"), 'Confirmed lead event subscription missing');
assert(script.includes("trackConversionEvent('generate_lead'"), 'GA4 generate_lead event missing');
assert(funnelLogic.includes("data.success !== true"), 'Do not count unsaved form requests');
assert(funnelLogic.includes("window.dispatchEvent(new CustomEvent('appiex:lead_received'"), 'Only server receipt should trigger lead event');
console.log('72-hour campaign QA passed: offers, attribution, security semantics, noindex and confirmed lead tracking.');
